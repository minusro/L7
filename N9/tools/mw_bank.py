#!/usr/bin/env python3
# mw_bank.py — generates n9_mw_bank.h from the Waldorf Microwave 1 factory
# bank (N9/sounds/Microwave soundbank/Factory.ęsb): 256 sounds of 256 bytes,
# the name at bytes 240-255.
#
# No MW1 dump spec was found, so the parameter offsets were inferred from the
# 256 factory patches themselves (pads vs percussive names, and the "303"
# patches as ground truth: cutoff 45-127, resonance 127, filter env 127,
# sustain 0): 25 wavetable (0-63), 26 start wave, 47 VCF cutoff,
# 48 resonance, 49 VCF env amount, 116 VCF env decay, 119-122 VCA ADSR.
# Treat them as provisional; re-run this tool if a real spec surfaces.
#
#   python3 tools/mw_bank.py "sounds/Microwave soundbank/Factory.ęsb" n9_mw_bank.h
import sys

def main(bank_path, out_path):
    d = open(bank_path, 'rb').read()
    assert len(d) == 65536, 'expected a 64 KB bank'
    with open(out_path, 'w') as f:
        f.write('// n9_mw_bank.h — generated by tools/mw_bank.py from the Microwave factory\n')
        f.write('// bank (sounds/Microwave soundbank). Do not edit; run the tool again.\n')
        f.write('// Offsets are inferred from the data, not a spec: see the tool.\n')
        f.write('#pragma once\n#include <stdint.h>\n\n')
        f.write('constexpr uint16_t MW_SOUNDS = 256;\n\n')
        f.write('struct MWSound {\n'
                '  char name[14];\n'
                '  uint8_t wt, startWave;          // wavetable 0-63, start wave 0-63\n'
                '  uint8_t cutoff, reso, fenvAmt, fdec;   // VCF (0-127)\n'
                '  uint8_t a, dec, s, r;           // VCA ADSR (0-127)\n'
                '};\n\n')
        f.write('PROGMEM const MWSound MW_BANK[256] = {\n')
        for i in range(256):
            r = d[i * 256:(i + 1) * 256]
            name = ''.join(chr(c) if 32 <= c < 127 else ' ' for c in r[240:253]).rstrip()
            name = name.replace('\\', '\\\\').replace('"', '\\"')
            f.write('    {"%s", %d, %d, %d, %d, %d, %d, %d, %d, %d, %d},\n' % (
                name, min(63, r[25]), min(63, r[26]), r[47] & 127, r[48] & 127,
                r[49] & 127, r[116] & 127, r[119] & 127, r[120] & 127, r[121] & 127, r[122] & 127))
        f.write('};\n')
    print(f'wrote {out_path}: 256 sounds')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
